// scripts/extractData.js
// Run: node scripts/extractData.js
// Reads Master Data (local).xlsx and writes src/generatedData.ts

const XLSX = require('xlsx');
const fs = require('fs');
const path = require('path');

const wb = XLSX.readFile(path.join(__dirname, '..', 'Master Data (local).xlsx'));

// Title-case a string: "APOLLO JUBILEE HILLS" → "Apollo Jubilee Hills"
function toTitle(str) {
  const lower = ['And', 'Of', 'The', 'In', 'At', 'For', 'A', 'By', 'To', 'With', 'De'];
  return String(str).trim().replace(/\w+/g, (w, i) => {
    const cap = w[0].toUpperCase() + w.slice(1).toLowerCase();
    return (i > 0 && lower.includes(cap)) ? cap.toLowerCase() : cap;
  });
}

// ── HOSPITALS BY CITY ────────────────────────────────────────────────────
const locs = XLSX.utils.sheet_to_json(wb.Sheets['Location']);
const byCity = {};
for (const r of locs) {
  if (!r['AA City'] || r['Status'] !== 'Active') continue;
  const city = toTitle(r['AA City']);
  const locId = r['AA location ID'] ? String(r['AA location ID']).trim() : '';
  const hospitalName = toTitle(r['Name']);
  if (!byCity[city]) byCity[city] = [];
  byCity[city].push({
    name: hospitalName,
    city,
    locationId: locId,
    url: `https://www.apollohospitals.com/doctors/?location=${encodeURIComponent(city)}`,
  });
}

// ── SPECIALITIES ─────────────────────────────────────────────────────────
const specRows = XLSX.utils.sheet_to_json(wb.Sheets['Speciality']);
const specialities = specRows
  .filter(s => s['Status'] === 'Active' && s['AA Specialty ID'] && !String(s['Name']).includes('Test'))
  .map(s => ({
    name: toTitle(s['Name']),
    aaId: String(s['AA Specialty ID']).trim(),
  }))
  .sort((a, b) => a.name.localeCompare(b.name));

// ── DOCTORS ───────────────────────────────────────────────────────────────
const docRows = XLSX.utils.sheet_to_json(wb.Sheets['Doctor']);
const nameRegex = /^[A-Za-z\s.\-']{5,60}$/;
const doctors = docRows
  .filter(d => {
    if (d['Status'] !== 'Active') return false;
    const full = String(d[' Full Name'] || '').trim();
    if (full.length < 5 || full.length > 60) return false;
    if (/^(aaa|test|xxx|zzz|\.|,)/i.test(full)) return false;
    if (!nameRegex.test(full)) return false;
    const id = String(d['Doctor Identifier'] || '');
    if (!/^\d+$/.test(id)) return false; // only numeric IDs are real
    return true;
  })
  .map(d => ({
    name: toTitle(d[' Full Name']),
    id: String(d['Doctor Identifier']).trim(),
  }));

console.log(`Hospitals: ${Object.values(byCity).flat().length} across ${Object.keys(byCity).length} cities`);
console.log(`Specialities: ${specialities.length}`);
console.log(`Doctors: ${doctors.length}`);
console.log('Sample cities:', Object.keys(byCity).sort().join(', '));
console.log('Sample specialities:', specialities.slice(0,5).map(s=>s.name));
console.log('Sample doctors:', doctors.slice(0,5).map(d=>d.name));

// ── WRITE generatedData.ts ────────────────────────────────────────────────
const out = `// AUTO-GENERATED by scripts/extractData.js – DO NOT EDIT MANUALLY
// Source: Master Data (local).xlsx — ${doctors.length} doctors, ${specialities.length} specialities, ${Object.values(byCity).flat().length} hospitals across ${Object.keys(byCity).length} cities

export interface GeneratedHospital {
  name: string;
  city: string;
  locationId: string;
  url: string;
}

export interface GeneratedSpeciality {
  name: string;
  /** Apollo Appointments AA Specialty ID */
  aaId: string;
}

export interface GeneratedDoctor {
  name: string;
  id: string;
}

export const hospitalsByCity: Record<string, GeneratedHospital[]> = ${JSON.stringify(byCity, null, 2)};

export const specialities: GeneratedSpeciality[] = ${JSON.stringify(specialities, null, 2)};

export const doctors: GeneratedDoctor[] = ${JSON.stringify(doctors, null, 2)};

export const allCities: string[] = ${JSON.stringify(Object.keys(byCity).sort(), null, 2)};
`;

const outPath = path.join(__dirname, '..', 'src', 'generatedData.ts');
fs.writeFileSync(outPath, out, 'utf8');
console.log('Written to src/generatedData.ts');
